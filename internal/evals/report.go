// LoadReport reads a results file written by Overhead or Live; exactly one
// of the returned reports is non-nil.
func LoadReport(path string) (*OverheadReport, *LiveReport, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, nil, err
	}
	var kind struct {
		Kind string `json:"kind"`
	}
	if err := json.Unmarshal(data, &kind); err != nil {
		return nil, nil, fmt.Errorf("%s: %w", path, err)
	}
	switch kind.Kind {
	case "overhead":
		var r OverheadReport
		err = json.Unmarshal(data, &r)
		return &r, nil, err
	case "live":
		var r LiveReport
		err = json.Unmarshal(data, &r)
		return nil, &r, err
	}
	return nil, nil, fmt.Errorf("%s: unknown results kind %q", path, kind.Kind)
}

// PageTitle is the heading of the published benchmark page.
const PageTitle = "Benchmarks"

// RenderPage renders the published benchmark page from an overhead run and,
// when given, a live run.
func RenderPage(overhead *OverheadReport, live *LiveReport) string {
	var b strings.Builder
	b.WriteString("# " + PageTitle + "\n\n")
	b.WriteString("Generated by `make evals-publish` from `evals/results/`. The method is in `evals/README.md`.\n\n")
	if overhead != nil {
		b.WriteString(RenderOverhead(overhead, "##"))
	}
	if live != nil {
		b.WriteString("\n" + RenderLive(live, "##"))
	}
	b.WriteString("\n## Reproduce\n\n```bash\nmake evals                                   # overhead against the mock model\nmake evals-live MODE=auto,speed,quality      # live tasks, one row per routing mode\nmake evals-publish                           # regenerate this page\n```\n\n")
	b.WriteString("Results depend on the machine. Compare numbers from one run on one machine only.\n")
	return b.String()
}

func fmtMs(v float64) string { return fmt.Sprintf("%.1f ms", v) }

// thousands formats n with comma separators.
func thousands(n int) string {
	s := fmt.Sprint(n)
	if n < 0 {
		return "-" + thousands(-n)
	}
	for i := len(s) - 3; i > 0; i -= 3 {
		s = s[:i] + "," + s[i:]
	}
	return s
}

// RenderOverhead renders an overhead run as Markdown under heading level h.
func RenderOverhead(r *OverheadReport, h string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s Overhead\n\n", h)
	b.WriteString("wopr talks to a local mock model that answers every request with one fixed reply over OpenAI Chat Completions, " +
		"OpenAI Responses, or Anthropic Messages, so the model adds no time or variance. What remains is wopr: process startup, " +
		"request construction, streaming, Session I/O, and teardown. These numbers say nothing about model quality.\n\n")
	fmt.Fprintf(&b, "`%s`, measured %s on %s/%s (%d CPUs, %s). Each scenario ran %d warm-up and %d measured runs. Prompt: `%s`.\n\n",
		r.Version, r.Generated, r.Host.OS, r.Host.Arch, r.Host.CPUs, r.Host.Go, r.Warmup, r.Runs, r.Prompt)
	b.WriteString("| Scenario | Median | p90 | CPU | Peak RSS | Requests | First request | System prompt | Tools |\n")
	b.WriteString("|---|---:|---:|---:|---:|---:|---:|---:|---:|\n")
	var failed []string
	for _, s := range r.Results {
		title := s.Title
		if s.Scenario == "resumed-session" {
			title += fmt.Sprintf(" (%s exchanges)", thousands(r.SessionExchanges))
		}
		if s.Runs == 0 {
			failed = append(failed, title)
			continue
		}
		reqs, first, system, tools := "", "", "", ""
		if s.Requests > 0 {
			reqs, first, system, tools = fmt.Sprint(s.Requests), thousands(s.RequestBytes)+" B", thousands(s.SystemBytes)+" B", fmt.Sprint(s.Tools)
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %.1f MiB | %s | %s | %s | %s |\n", title, fmtMs(s.WallMsMedian), fmtMs(s.WallMsP90), fmtMs(s.CPUMsMedian), s.RSSMiBMedian, reqs, first, system, tools)
	}
	if len(failed) > 0 {
		fmt.Fprintf(&b, "\nDid not complete: %s. The JSON results record each failure.\n", strings.Join(failed, "; "))
	}
	b.WriteString("\nPeak RSS is the largest single process in wopr's process tree. Request sizes are HTTP request body bytes.\n")
	return b.String()
}

// RenderLive renders a live run as Markdown under heading level h.
func RenderLive(r *LiveReport, h string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s Live tasks\n\n", h)
	fmt.Fprintf(&b, "`%s`, measured %s, %d run(s) of %d task(s) per configuration. Every run starts a fresh session in a copy of the task. "+
		"A run passes when the task's check succeeds and no protected file changed; a run cut off at its time limit is still judged, and those passes are counted separately. "+
		"The pass rate's interval is the 95%% Wilson score interval over all attempts.\n\n",
		r.Version, r.Generated, r.Runs, len(r.Tasks))
	b.WriteString("| Configuration | Pass rate | 95% CI | Passed at cutoff | Cost | Cost per pass | Tokens in per task | Cached per task | Tokens out per task | Turns per task | Tool calls per task | Median wall time | Total wall time | Models (turns) |\n")
	b.WriteString("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|\n")
	for _, s := range r.Summary {
		perPass := "n/a"
		if s.CostPerPass != nil {
			perPass = fmt.Sprintf("$%.4f", *s.CostPerPass)
		}
		var models []string
		for _, m := range slices.Sorted(maps.Keys(s.Models)) {
			models = append(models, fmt.Sprintf("%s (%d)", m, s.Models[m]))
		}
		fmt.Fprintf(&b, "| %s | %.1f%% (%d/%d) | %.1f–%.1f%% | %d | $%.4f | %s | %s | %s | %s | %.1f | %.1f | %.1f s | %.0f s | %s |\n", s.Config, s.PassRate, s.Passed, s.Attempts,
			s.PassRateLow, s.PassRateHigh, s.PassedAtCutoff, s.CostUSD, perPass, thousands(int(s.InputTokens)), thousands(int(s.CachedTokens)), thousands(int(s.OutputTokens)),
			s.Turns, s.ToolCalls, s.WallSMedian, s.WallSTotal, strings.Join(models, ", "))
	}
	b.WriteString("\nTasks: " + strings.Join(r.Tasks, ", ") + ".\n")
	b.WriteString("\nCost is what providers reported; free and subscription models report $0. Tokens in include cache reads and writes.\n")
	return b.String()
}
